namespace TemplateService.Domain.Primitives;

/// <summary>
/// Базовый класс для Value Object (объектов‑значений) в стиле DDD.
/// 
/// Зачем нужен:
/// - Value Object — это тип, у которого равенство определяется по состоянию (значениям полей), а не по ссылке.
///   Например, два адреса с одинаковыми данными — это один и тот же адрес, даже если это разные экземпляры в памяти.
/// - Этот базовый класс даёт всем ValueObject‑ам единообразную реализацию Equals и GetHashCode,
///   избавляя от дублирования кода в каждом конкретном ValueObject (Address, Name и т.п.).
/// - Это напрямую связано с темой агрегатов и инвариантов, которую вы разбирали: ValueObject помогает
///   гарантировать корректность данных и предсказуемое поведение при сравнениях внутри агрегатов.
/// </summary>
public abstract class ValueObject
{
    /// <summary>
    /// Абстрактный метод, который каждый наследник должен реализовать.
    /// Он возвращает набор компонентов, определяющих «суть» ValueObject — по ним будет проверяться равенство.
    /// 
    /// Пример: для класса Address это будут Street, City, ZipCode и т.д.
    /// Реализация выглядит примерно так:
    /// protected override IEnumerable<object> GetEqualityComponents()
    /// {
    ///     yield return Street;
    ///     yield return City;
    ///     yield return ZipCode;
    /// }
    /// </summary>
    protected abstract IEnumerable<object> GetEqualityComponents();

    /// <summary>
    /// Переопределяет стандартное сравнение объектов.
    /// Реализует структурное равенство для ValueObject: два объекта равны, если:
    /// - они не null,
    /// - имеют одинаковый тип (чтобы, например, Address не был равен Name),
    /// - и их компоненты равенства совпадают по порядку и значению (SequenceEqual).
    /// </summary>
    /// <param name="obj">Объект для сравнения.</param>
    /// <returns>True, если объекты структурно равны; иначе false.</returns>
    public override bool Equals(object? obj)
    {
        // Если передан null или тип не совпадает — объекты не равны.
        // Проверка типа важна: это предотвращает сравнение разных ValueObject между собой.
        if (obj is null || obj.GetType() != GetType())
        {
            return false;
        }

        var other = (ValueObject)obj;
        // Сравниваем компоненты равенства поэлементно.
        return GetEqualityComponents().SequenceEqual(other.GetEqualityComponents());
    }

    /// <summary>
    /// Переопределяет вычисление хэш‑кода для корректной работы ValueObject в коллекциях:
    /// Dictionary, HashSet, LINQ‑операции с группировкой и т.д.
    /// 
    /// Логика:
    /// - Берём все компоненты равенства через GetEqualityComponents().
    /// - Для каждого компонента получаем его GetHashCode() (если компонент null — берём 0).
    /// - Объединяем все хэш‑коды с помощью XOR (^).
    /// 
    /// Важно: если Equals возвращает true, то и GetHashCode у двух объектов обязан быть одинаковым.
    /// Эта реализация гарантирует такое поведение.
    /// </summary>
    /// <returns>Хэш‑код, вычисленный на основе компонентов равенства.</returns>
    public override int GetHashCode()
    {
        return GetEqualityComponents()
            .Select(x => x?.GetHashCode() ?? 0)      // Защита от null, получение хэш‑кода каждого компонента
            .Aggregate((x, y) => x ^ y);             // Комбинирование через XOR
    }
}

// Как это связано с тем, что вы делали раньше
// С конвертерами EF Core. В предыдущих конфигурациях вы использовали HasConversion(ValueObjectConverters.Name) и т.п. Там EF Core берёт ValueObject (например, Name), вызывает .Value, чтобы сохранить в БД строку, и при чтении создаёт новый Name через Create(value). При этом внутри домена вы можете спокойно сравнивать два Name через == / .Equals, и сравнение будет работать по смыслу (по содержимому), а не по ссылке — благодаря этой реализации ValueObject.

// С агрегатами и инвариантами. В агрегате вы часто проверяете, не дублируется ли что‑то, не нарушены ли правила. Структурное равенство ValueObject делает такие проверки понятными и надёжными: например, «такой адрес уже есть» — это именно про смысл адреса, а не про то, тот ли это экземпляр в памяти.

// С тестами по агрегатам и границам. При написании тестов на агрегаты вы сможете проверять ожидаемые состояния через сравнение ValueObject, и тесты будут стабильными: не важно, каким именно экземпляром вы создали объект — если данные совпадают, он считается равным.